#!/usr/bin/env node

import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "packages/mcp/knowledge/developer-guidance.json");
const outputPath = path.join(root, "packages/mcp/src/developer-guidance.generated.ts");
const command = process.argv[2] ?? "check";

if (!new Set(["generate", "check"]).has(command)) {
  throw new Error("Usage: node scripts/generate-mcp-guidance.mjs <generate|check>");
}

const sourceText = await readFile(sourcePath, "utf8");
const guidance = JSON.parse(sourceText);
validateGuidance(guidance);

const sourceHash = createHash("sha256").update(sourceText).digest("hex");
const rendered =
  `// Generated by scripts/generate-mcp-guidance.mjs. Do not edit.\n` +
  `export const DATA_SHAPE_FORMATS = ${JSON.stringify(guidance.scaffold.formats)} as const;\n` +
  `export const DATA_TIME_UNITS = ${JSON.stringify(guidance.scaffold.timeUnits)} as const;\n` +
  `export const DEVELOPER_GUIDANCE = ${JSON.stringify(guidance, null, 2)} as const;\n`;

if (command === "generate") {
  await writeFile(outputPath, rendered);
  console.log(
    `Generated MCP developer guidance ${sourceHash.slice(0, 12)} ` +
      `(${guidance.failureModes.length} failure modes).`,
  );
} else {
  const existing = existsSync(outputPath) ? await readFile(outputPath, "utf8") : "";
  if (existing !== rendered) {
    throw new Error(
      "The generated MCP developer guidance is stale. " + "Run `pnpm run mcp:guidance`.",
    );
  }
  console.log(
    `Checked MCP developer guidance ${sourceHash.slice(0, 12)} ` +
      `(${guidance.failureModes.length} failure modes).`,
  );
}

function validateGuidance(value) {
  if (!value || typeof value !== "object" || value.schemaVersion !== 1) {
    throw new Error("developer-guidance.json must use schemaVersion 1");
  }
  assertStringArray(value.scaffold?.formats, "scaffold.formats");
  assertStringArray(value.scaffold?.timeUnits, "scaffold.timeUnits");
  if (!value.scaffold?.defaults?.line || !value.scaffold?.defaults?.stock) {
    throw new Error("developer-guidance.json is missing scaffold defaults");
  }
  if (!Array.isArray(value.failureModes) || value.failureModes.length === 0) {
    throw new Error("developer-guidance.json must contain failure modes");
  }

  const ids = new Set();
  for (const mode of value.failureModes) {
    if (!mode || typeof mode !== "object" || !nonEmpty(mode.id)) {
      throw new Error("Every failure mode needs a non-empty id");
    }
    if (ids.has(mode.id)) throw new Error(`Duplicate failure mode id: ${mode.id}`);
    ids.add(mode.id);
    for (const field of ["title", "symptom", "cause"]) {
      if (!nonEmpty(mode[field])) {
        throw new Error(`${mode.id}.${field} must be a non-empty string`);
      }
    }
    for (const field of ["components", "keywords", "checks", "fixes"]) {
      assertStringArray(mode[field], `${mode.id}.${field}`);
    }
    if (!mode.components.every((component) => ["line", "stock"].includes(component))) {
      throw new Error(`${mode.id}.components contains an unknown component`);
    }
    if (
      !mode.snippet ||
      !nonEmpty(mode.snippet.language) ||
      !nonEmpty(mode.snippet.label) ||
      !nonEmpty(mode.snippet.code)
    ) {
      throw new Error(`${mode.id}.snippet is incomplete`);
    }
  }
}

function assertStringArray(value, label) {
  if (!Array.isArray(value) || value.length === 0 || !value.every(nonEmpty)) {
    throw new Error(`${label} must be a non-empty string array`);
  }
}

function nonEmpty(value) {
  return typeof value === "string" && value.trim().length > 0;
}
