#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mode = process.argv[2] ?? "check";
if (mode !== "check" && mode !== "write") {
  throw new Error("Usage: generate-theme-subpaths.mjs [check|write]");
}

const builtCatalogUrl = pathToFileURL(path.join(root, "packages/themes/dist/index.js"));
builtCatalogUrl.searchParams.set("generated", String(Date.now()));
const { PUBLIC_THEME_IDS, PUBLIC_THEMES } = await import(builtCatalogUrl.href);

const targets = [
  {
    kind: "line",
    exportName: "LINE_THEME_DATA",
    file: path.join(root, "packages/themes/src/lineCatalog.generated.ts"),
  },
  {
    kind: "stock",
    exportName: "STOCK_THEME_DATA",
    file: path.join(root, "packages/themes/src/stockCatalog.generated.ts"),
  },
];

let mismatch = false;
for (const target of targets) {
  const data = Object.fromEntries(
    PUBLIC_THEME_IDS.map((id) => {
      const preset = PUBLIC_THEMES[id];
      return [
        id,
        {
          id: preset.id,
          label: preset.label,
          colorScheme: preset.colorScheme,
          [target.kind]: preset[target.kind],
        },
      ];
    }),
  );
  const source = generatedSource(target.kind, target.exportName, data);
  if (mode === "write") {
    await writeFile(target.file, source, "utf8");
    process.stdout.write(
      `Generated ${path.relative(root, target.file)} from the canonical theme catalog.\n`,
    );
    continue;
  }

  const current = await readFile(target.file, "utf8").catch(() => "");
  if (current !== source) {
    mismatch = true;
    process.stderr.write(
      `${path.relative(root, target.file)} is stale. Run pnpm run themes:generate.\n`,
    );
  }
}

if (mismatch) process.exitCode = 1;

function generatedSource(kind, exportName, data) {
  const property = kind === "line" ? "line" : "stock";
  return `// Generated by scripts/generate-theme-subpaths.mjs. Do not edit directly.
import type { DeepReadonly } from "@sixtyfold/core";
import type { ChartThemeId } from "./themeIds.js";

export interface Generated${capitalize(kind)}ThemeData {
  id: ChartThemeId;
  label: string;
  colorScheme: "dark" | "light";
  ${property}: unknown;
}

function deepFreeze<T>(value: T): DeepReadonly<T> {
  if (value !== null && typeof value === "object" && !Object.isFrozen(value)) {
    for (const child of Object.values(value as Record<string, unknown>)) {
      deepFreeze(child);
    }
    Object.freeze(value);
  }
  return value as DeepReadonly<T>;
}

export const ${exportName}: DeepReadonly<
  Record<ChartThemeId, Generated${capitalize(kind)}ThemeData>
> = deepFreeze(${JSON.stringify(data)});
`;
}

function capitalize(value) {
  return `${value[0].toUpperCase()}${value.slice(1)}`;
}
